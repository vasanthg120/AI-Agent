// Writes src/dialer/components/icons.tsx: the few Feather icons the Dialer's
// first screen uses, as plain SVG components. react-icons' Feather set is one
// module, so importing even one icon from it brings every Feather icon the main
// app uses into the Dialer's first download. Same drawings (Feather, MIT
// licence), a fraction of the bytes. Add a name below and run
// `node scripts/build-dialer-icon-set.mjs` to get another.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ICONS = [
  'FiAlertCircle',
  'FiAlertTriangle',
  'FiArrowLeft',
  'FiAward',
  'FiBell',
  'FiBriefcase',
  'FiCheck',
  'FiChevronDown',
  'FiChevronLeft',
  'FiChevronRight',
  'FiClipboard',
  'FiClock',
  'FiDelete',
  'FiDownload',
  'FiExternalLink',
  'FiGlobe',
  'FiInfo',
  'FiLock',
  'FiLogOut',
  'FiMoreHorizontal',
  'FiPhone',
  'FiPhoneCall',
  'FiPhoneIncoming',
  'FiPhoneMissed',
  'FiPhoneOff',
  'FiPhoneOutgoing',
  'FiPlusSquare',
  'FiRefreshCw',
  'FiSearch',
  'FiSettings',
  'FiShare',
  'FiShield',
  'FiUser',
  'FiUsers',
  'FiWifiOff',
  'FiX',
];

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'node_modules/react-icons/fi/index.mjs'), 'utf8');
const ATTR_NAMES = { 'fill-rule': 'fillRule', 'clip-rule': 'clipRule' };

function jsx(node) {
  const attrs = Object.entries(node.attr)
    .map(([key, value]) => `${ATTR_NAMES[key] ?? key}="${value}"`)
    .join(' ');
  const children = node.child.map(jsx).join('');
  return children ? `<${node.tag} ${attrs}>${children}</${node.tag}>` : `<${node.tag} ${attrs} />`;
}

const components = ICONS.map((name) => {
  const match = new RegExp(`export function ${name} \\(props\\) \\{\\s*return GenIcon\\((\\{.*\\})\\)\\(props\\);`).exec(source);
  if (!match) throw new Error(`${name} not found in react-icons/fi`);
  const tree = JSON.parse(match[1]);
  return `export const ${name} = (props: IconProps) => <Icon {...props}>${tree.child.map(jsx).join('')}</Icon>;`;
});

const out = `// Generated by scripts/build-dialer-icon-set.mjs — do not edit by hand.
// Feather icons (https://feathericons.com, MIT licence) as plain SVG, so the
// Dialer's first download carries only the icons it shows.

import type { ReactNode, SVGProps } from 'react';

type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, ...props }: IconProps & { children: ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      width="1em"
      height="1em"
      aria-hidden
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

${components.join('\n')}
`;
writeFileSync(join(root, 'src/dialer/components/icons.tsx'), out);
console.log(`Wrote ${ICONS.length} icons.`);
